#ifndef SCANTAILOR_CORE_STYLESHEETCOLORSCHEME_H_
#define SCANTAILOR_CORE_STYLESHEETCOLORSCHEME_H_

#include <QColor>
#include <QPalette>
#include <QString>
#include <memory>

#include "ColorScheme.h"

/**
 * A color scheme of the Fusion style with its own palette and style sheet: Light and Dark. Both
 * are built the same way from the same meanings of colors; only their color tables differ.
 */
class StyleSheetColorScheme : public ColorScheme {
 public:
  /**
   * The colors of the scheme that the palette and the color parameters are made of, one for each
   * meaning (see src/resources/color_schemes/light.colors).
   */
  struct Colors {
    QColor window;
    QColor content;
    QColor border;
    QColor text;
    QColor disabledText;
    QColor lightTextOnAccent;
    QColor darkTextOnAccent;
    QColor error;
    QColor link;
    QColor imageView;
    QColor inactiveSelection;
  };

  QStyle* getStyle() const override;

  const QPalette* getPalette() const override;

  const QString* getStyleSheet() const override;

  const ColorParams* getColorParams() const override;

  /**
   * The color of text and marks on \p accent: of \p lightText and \p darkText the one with more contrast
   * to it, so that a chosen accent color of any lightness stays readable.
   */
  static QColor textOnAccent(const QColor& accent, const QColor& lightText, const QColor& darkText);

  /**
   * The color parameters (ColorScheme::getColorParams()) of these colors, the accent color and the
   * text on it. The native scheme takes them by the same meanings from the system's palette.
   */
  static ColorParams colorParams(const Colors& colors, const QColor& accent, const QColor& onAccent);

  /**
   * The scheme of a color table generated by cmake/ColorSchemes.cmake, e.g.
   * StyleSheetColorScheme::of<light_scheme_colors>() from color_schemes/light_scheme_colors.h.
   */
  template <typename Table>
  static std::unique_ptr<StyleSheetColorScheme> of();

 private:
  /**
   * \param name The name of the scheme, which is also the prefix of its resources.
   * \param defaultAccentColor The accent color unless the user chose another one.
   */
  StyleSheetColorScheme(const Colors& colors, const QString& name, const char* defaultAccentColor);

  void loadPalette(const Colors& colors, const QColor& accent, const QColor& onAccent);

  /** \param lightMarks Whether the marks on the accent color are the light ones. */
  void loadStyleSheet(const QString& path, bool lightMarks);

  QPalette m_palette;
  QString m_styleSheet;
  ColorParams m_customColors;
};

template <typename Table>
std::unique_ptr<StyleSheetColorScheme> StyleSheetColorScheme::of() {
  Colors colors;
  colors.window = QColor(Table::window);
  colors.content = QColor(Table::content);
  colors.border = QColor(Table::border);
  colors.text = QColor(Table::text);
  colors.disabledText = QColor(Table::disabledText);
  colors.lightTextOnAccent = QColor(Table::lightTextOnAccent);
  colors.darkTextOnAccent = QColor(Table::darkTextOnAccent);
  colors.error = QColor(Table::error);
  colors.link = QColor(Table::link);
  colors.imageView = QColor(Table::imageView);
  colors.inactiveSelection = QColor(Table::inactiveSelection);
  // The constructor is private, so std::make_unique can't call it.
  return std::unique_ptr<StyleSheetColorScheme>(
      new StyleSheetColorScheme(colors, QString::fromUtf8(Table::name), Table::accent));
}

#endif  // SCANTAILOR_CORE_STYLESHEETCOLORSCHEME_H_
